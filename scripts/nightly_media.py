def enqueue(queue, keys, snapshot):
    """Use the approved export snapshot for adult status, preserving each queued item."""
    if not keys.is_file():
        raise FileNotFoundError(f"出荷済みキーが見つからない: {keys}")
    exported_keys = keys.read_text(encoding="utf-8").splitlines()
    if not exported_keys:
        return
    with contextlib.closing(sqlite3.connect(snapshot.resolve().as_uri() + "?mode=ro", uri=True)) as ledger:
        adult = dict(ledger.execute("SELECT key,adult FROM llm_judgement WHERE review_state='approved'"))
    ready = favicon.now_iso()
    rows = []
    for key in exported_keys:
        if key not in adult:
            raise ValueError(f"出荷時の判定が無い: {key}")
        site_id = export_approved_sql.site_id(key)
        rows.append(("favicon", site_id, ready))
        if adult[key] != "yes":
            rows.append(("thumbnail", site_id, ready))
    queue.executemany("INSERT OR IGNORE INTO pending(kind,site_id,retry_at) VALUES(?,?,?)", rows)
    queue.commit()


def d1(name, *args):
    return subprocess.run(
        [shutil.which("npx") or "npx", "wrangler", "d1", "execute", name, "--remote", *args],
        cwd=ROOT, check=True, capture_output=True, text=True, timeout=120,
    ).stdout


def listed_sites(name, ids, kind):
    # The list contains only stable IDs generated by site_id(). Split the query to fit Windows command-line limits.
    col = {"favicon": "favicon_path", "thumbnail": "thumb_path"}[kind]
    rows = []
    for i in range(0, len(ids), 40):
        wanted = ",".join(export_approved_sql.q(site_id) for site_id in ids[i:i + 40])
        sql = f"SELECT id,url FROM sites WHERE id IN ({wanted}) AND {col} IS NULL;"
        result = json.loads(d1(name, "--json", "--command", sql))
        if len(result) != 1 or not result[0].get("success"):
            raise ValueError("D1 から掲載中のサイトを読めなかった")
        rows.extend(result[0]["results"])
    return rows


def retry_dates(db, table, ids, now, upload_failures=()):
    """Drop manually excluded IDs and reuse the acquisition tools' existing retry deadlines."""
    scope, params = favicon.site_filter(ids)
    tomorrow = (now + datetime.timedelta(days=1)).replace(hour=0, minute=0, second=0, microsecond=0)
    cutoff = favicon.now_iso(now)
    fallback = favicon.now_iso(tomorrow)
    rows = db.execute(f"SELECT site_id,exclude,next_check_at FROM {table} WHERE 1{scope}", params)
    retry = {}
    for row in rows:
        site_id = row["site_id"]
        if row["exclude"]:
            continue
        due = row["next_check_at"]
        # An image already saved locally can be uploaded again tomorrow without recapturing.
        retry[site_id] = due if due and due > cutoff and site_id not in upload_failures else fallback
    return retry


def wsl_path(distro, path):
    p = subprocess.run(['wsl.exe', '-d', distro, '--exec', 'wslpath', '-a', '-u', str(Path(path).resolve())],
                       capture_output=True, check=True, timeout=60)
    return p.stdout.decode('utf-8').strip()


def capture_in_wsl(args, db_path, store_dir, sites, ids):
    """Run only the existing sandboxed capture in WSL; upload remains on Windows."""
    path = args.out / 'thumbnail-sites.json'
    path.write_text(json.dumps(sites, ensure_ascii=False), encoding='utf-8')
    distro = args.wsl_distro
    cwd, db, store, selected = [wsl_path(distro, p) for p in (ROOT, db_path, store_dir, path)]
    cmd = ['wsl.exe', '-d', distro, '--cd', cwd, '--exec', 'bash', '-lc',
           'set -e; p="$1"; c="$2"; case "$p" in /*) ;; *) p="$HOME/$p";; esac; '
           'case "$c" in /*) ;; *) c="$HOME/$c";; esac; '
           'PLAYWRIGHT_DIR=$(readlink -e -- "$p"); CHROMIUM_PATH=$(readlink -e -- "$c"); '
           'export PLAYWRIGHT_DIR CHROMIUM_PATH; shift 2; '
           'exec uv run --no-project --with pillow python3 scripts/thumbnail/thumbnail.py "$@"',
           'mise-thumbnail', args.wsl_playwright, args.wsl_chromium,
           '--db', db, 'run', '--apply', '--store-dir', store, '--only-sites', selected, '--limit', str(len(ids))]
    # Record before spawn: a killed Windows parent can leave its Linux child alive.
    # Keep the marker after timeout or abrupt termination; never guess the child is gone.
    marker = args.var / 'nightly' / 'media-worker-stopped.txt'
    try:
        with marker.open('x', encoding='utf-8') as flag:
            flag.write('WSL capture may still be running. Inspect and stop it before clearing this file.\n')
    except FileExistsError as e:
        raise RuntimeError(f'撮影の中断状態を確認: {marker}') from e
    try:
        # Allow every requested site all redirect checks, each full capture and robots request,
        # even if they serialize on one host. DNS is not bounded by these per-request limits.
        timeout = 600 + len(ids) * (thumbnail.MAX_URL_CHECKS + 1) * (
            thumbnail.CAPTURE_TIMEOUT + thumbnail.fetcher.TIMEOUT + thumbnail.fetcher.MAX_CRAWL_DELAY)
        result = subprocess.run(cmd, check=False, timeout=timeout)
    except subprocess.TimeoutExpired:
        raise
    except Exception:
        # Spawn failure cannot safely prove that no child survived.
        raise
    else:
        if result.returncode:
            # A failed Python child can leave detached Linux grandchildren; inspect first.
            raise subprocess.CalledProcessError(result.returncode, cmd)
        marker.unlink()


def capture_thumbnails(args, sites, ids, now):
    db_path = args.var / "thumbnails.sqlite"
    store_dir = args.var / "thumbnails"
    with contextlib.closing(thumbnail.connect(db_path)) as db:
        thumbnail.import_sites(db, [(s["id"], s["url"]) for s in sites])
        budget = min(len(ids), thumbnail.remaining_today(db, now, thumbnail.DEFAULT_PER_DAY))
        due = thumbnail.due_sites(db, now, budget, ids)
    if due and sys.platform == 'win32':
        capturer = thumbnail.NodeCapturer(sandbox=False, limits=False)
        capturer.check_upstream()
        if not capturer.playwright or not capturer.chromium:
            raise RuntimeError('サムネイル取得には Playwright と Chromium が必要')
        with contextlib.closing(thumbnail.connect(db_path)) as db:
            thumbnail.run(db, thumbnail.LocalDirStore(store_dir), capturer, now=now, limit=len(ids), site_ids=ids)
    elif due:
        if not shutil.which("bwrap"):
            raise RuntimeError("サムネイル取得には bwrap が必要")
        capturer = thumbnail.NodeCapturer()
        capturer.check_ready()
        capturer.check_upstream()
        if not capturer.playwright or not capturer.chromium:
            raise RuntimeError("サムネイル取得には Playwright と Chromium が必要")
        with contextlib.closing(thumbnail.connect(db_path)) as db:
            thumbnail.run(db, thumbnail.LocalDirStore(store_dir), capturer, now=now, limit=len(ids), site_ids=ids)
    with contextlib.closing(thumbnail.connect(db_path)) as db:
        upload_failures = set()
        thumbnail.upload(db, thumbnail.R2Store(remote=True), store_dir, apply=True, site_ids=ids,
                         on_store_failure=upload_failures.add)
        checked = [r["site_id"] for r in due]
        scope, params = favicon.site_filter(checked)
        errors = db.execute(f"SELECT site_id,last_error FROM thumbs WHERE last_checked_at>=?{scope}",
                            (favicon.now_iso(now), *params))
        store_failures = upload_failures | {r["site_id"] for r in errors
                                           if thumbnail.error_code(r["last_error"]) == "store_failed"}
        return (thumbnail.sql_updates(db, store="r2-remote", site_ids=ids),
                retry_dates(db, "thumbs", ids, now, upload_failures), store_failures)


def capture_favicons(args, sites, ids, now):
    with contextlib.closing(favicon.connect(args.var / "favicons.sqlite")) as db:
        favicon.import_sites(db, [(s["id"], s["url"]) for s in sites])
        store_failures = set()
        print("favicon", favicon.run(db, favicon.R2Store(remote=True), now=now, limit=len(ids),
                                     site_ids=ids, on_store_failure=store_failures.add))
        return (favicon.sql_updates(db, store="r2-remote", site_ids=ids),
                retry_dates(db, "favicons", ids, now), store_failures)


def process_queue(queue, args, kind, limit, capture):
    if limit == 0:
        return
    now = datetime.datetime.now(datetime.timezone.utc)
    cutoff = favicon.now_iso(now)
    ids = [row[0] for row in queue.execute(
        "SELECT site_id FROM pending WHERE kind=? AND retry_at<=? ORDER BY retry_at,rowid LIMIT ?",
        (kind, cutoff, limit),
    )]
    if not ids:
        return
    sites = listed_sites(args.d1_name, ids, kind)
    store_failures = set()
    pending = {}
    if sites:
        updates, retry, store_failures = capture(args, sites, [s["id"] for s in sites], now)
        if updates:
            sql = args.out / f"{kind}-updates.sql"
            sql.write_text(updates, encoding="utf-8")
            d1(args.d1_name, "--yes", "--file", str(sql))
        # Recheck D1. Leave eligible rows with no image, including capture failures and daily overflow.
        pending = {r["id"]: retry[r["id"]] for r in listed_sites(args.d1_name, list(retry), kind)}
    queue.executemany("UPDATE pending SET retry_at=? WHERE kind=? AND site_id=?",
                      [(ready, kind, site_id) for site_id, ready in pending.items()])
    queue.executemany("DELETE FROM pending WHERE kind=? AND site_id=?",
                      [(kind, site_id) for site_id in ids if site_id not in pending])
    queue.commit()
    print(f"{kind}: {len(ids)} 件中 {len(ids) - len(pending)} 件を処理、{len(pending)} 件を繰り越し")
    if store_failures:
        raise RuntimeError(f"画像保存に {len(store_failures)} 件失敗。成功分は反映済み")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--var", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--d1-name", required=True, choices=["mise"])
    ap.add_argument("--enqueue", action="store_true")
    ap.add_argument("--favicon-limit", type=int, required=True)
    ap.add_argument("--thumbnail-limit", type=int, required=True)
    ap.add_argument('--wsl-distro', help='Windows 上の隔離撮影に使う WSL2 ディストリビューション')
    ap.add_argument('--wsl-playwright', help='WSL 内の playwright ディレクトリの絶対パス')
    ap.add_argument('--wsl-chromium', help='WSL 内の Chromium 実行ファイルの絶対パス')
    a = ap.parse_args(argv)
    if not all(0 <= n <= 100 for n in (a.favicon_limit, a.thumbnail_limit)):
        ap.error("各画像の上限は 0–100 件")
    if a.thumbnail_limit and sys.platform not in ('linux', 'win32'):
        ap.error('サムネイル撮影は Linux または Windows が必要')
    import PIL  # noqa: F401  (依存が無ければ取得・書き込み前に停止)

    failed = False
    with (a.var / 'nightly' / '.media.lock').open('a+') as lock, contextlib.closing(sqlite3.connect(a.var / "nightly" / "media.sqlite")) as queue:
        filelock.lock(lock, blocking=False)
        queue.execute("CREATE TABLE IF NOT EXISTS pending ("
                      "kind TEXT, site_id TEXT, retry_at TEXT NOT NULL, PRIMARY KEY(kind,site_id))")
        if a.enqueue:
            enqueue(queue, a.out / "keys.txt", a.out / "export.sqlite")
        for kind, limit, capture in (("favicon", a.favicon_limit, capture_favicons),
                                     ("thumbnail", a.thumbnail_limit, capture_thumbnails)):
            try:
                process_queue(queue, a, kind, limit, capture)
            except subprocess.TimeoutExpired:
                raise
            except (OSError, ValueError, RuntimeError, sqlite3.Error, subprocess.SubprocessError) as e:
                print(f"{kind}: {e}", file=sys.stderr)
                failed = True
    return int(failed)


if __name__ == "__main__":
    sys.exit(main())
